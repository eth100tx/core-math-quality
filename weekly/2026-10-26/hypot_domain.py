"""Rigorous count enclosure, not enumeration of the restricted hypot domain.
Uses the exact rational pi enclosure generated by certify_polynomials.py.
"""
from fractions import Fraction as F
from math import isqrt,ceil
from pathlib import Path
import json,sys
from certify_polynomials import atan

def main():
    d=json.loads(Path(sys.argv[1]).read_text());pl,ph=F(d['pi_lower']),F(d['pi_upper'])
    l5,h5=atan(5);l239,h239=atan(239);D=1<<512
    assert pl==F(((16*l5-4*h239)*D).__floor__(),D)
    assert ph==F(ceil((16*h5-4*l239)*D),D)
    N=1<<52;D=1<<512;k=isqrt(3*D*D);sl,sh=F(k,D),F(k+1,D)
    assert sl*sl<3<sh*sh
    # A monotone lower-left grid approximates the admissible area from below.
    # Upper-right counting bounds the area from above; the monotone boundary
    # crosses at most 2*N cells. Equivalently the shifted grids differ only in
    # their two boundary rows/columns. Retain a conservative 2*N slack.
    lower=ceil((sl-ph/3)*N*N-2*N);upper=((sh-pl/3)*N*N).__floor__()
    z=isqrt(2*N*N);diagonal=2*N-(z if z*z==2*N*N else z+1)
    out={'N':N,'ordered_pairs_lower':lower,'ordered_pairs_upper':upper,
         'unordered_pairs_lower':ceil(F(lower+diagonal,2)),
         'unordered_pairs_upper':(upper+diagonal)//2,'diagonal_pairs':diagonal,
         'area':'sqrt(3)-pi/3','result_upper':'2*sqrt(2) < 4',
         'count_status':'rigorous enclosure; exact cardinality not enumerated',
         'idealized_single_core_years_at_1e9_four_mode_pairs_per_second_lower':str(F(lower,10**9*31557600)),
         'idealized_years_display':float(F(lower,10**9*31557600)),
         'scope':'positive binary64 x,y in [1,2), exact real hypot >=2. All four rounded results are in [2,4). Inputs with exact norm below2 that round up to2 are excluded.'}
    Path(sys.argv[2]).write_text(json.dumps(out,indent=2)+'\n');print(lower,upper)

if __name__=='__main__':main()
